"""Release Intelligence agent: release notes written from the graph.

Compares a crawl with the one before it (CHANGED_IN edges), groups the changes by page,
and follows them through the graph to everything they affected: which demos, videos,
guides and tests were rebuilt, which broke, and which still need attention.
"""

import datetime as dt
import secrets
import time
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import urlsplit

from . import queries as Q
from .config import settings
from .db import GraphStore
from .ids import origin
from .schema import apply_schema


@dataclass
class ReleaseNote:
    id: str
    crawl: str
    previous: str | None
    path: Path
    changes: int
    summary: str


def describe(kind: str, el_kind: str | None, page: str, old: str | None, new: str | None) -> str:
    what = el_kind or "element"
    if kind == "changed":
        return f"{what} “{old}” is now “{new}”"
    if kind == "added":
        return f"new {what} “{new}”"
    if kind == "removed":
        return f"{what} “{old}” was removed"
    if kind == "page_added":
        return "new page"
    if kind == "page_removed":
        return "page is gone"
    return kind


async def release_notes(store: GraphStore, root_url: str, crawl_id: str | None = None,
                        qa_summary: str | None = None) -> ReleaseNote:
    await apply_schema(store)
    if not crawl_id:
        row = await store.one(Q.LATEST_COMPLETED_CRAWL, {"site_id": origin(root_url)})
        if not row:
            raise RuntimeError("No completed crawl yet.")
        crawl_id = row[0]
    prev = await store.one(Q.PREVIOUS_CRAWL, {"crawl_id": crawl_id})
    changes = await store.query(Q.CRAWL_CHANGES, {"crawl_id": crawl_id})
    summary_row = await store.one(Q.CRAWL_SUMMARY, {"crawl_id": crawl_id})
    visited, unchanged = int(summary_row[2] or 0), int(summary_row[3] or 0)
    product = urlsplit(root_url).netloc

    by_page: dict[str, list[str]] = defaultdict(list)
    for kind, page, el_kind, _, old, new in changes:
        by_page[page or "?"].append(describe(kind, el_kind, page, old, new))
    pages_touched = len(by_page)
    if changes:
        first_page, first = next(iter(by_page.items()))
        summary = (f"{len(changes)} change{'s' * (len(changes) != 1)} on {pages_touched} page{'s' * (pages_touched != 1)}"
                   f", e.g. {first[0]} on {first_page}")
    else:
        summary = "No changes since the previous crawl."

    rebuilt = await store.query(Q.CRAWL_TRIGGERED, {"crawl_id": crawl_id})
    broken = await store.query(Q.CRAWL_BROKE, {"crawl_id": crawl_id})
    stale_demos = [r for r in await store.query(Q.DEMO_HEALTH) if r[5] == "current" and int(r[4] or 0) > 0]
    stale_suites = await store.query(Q.STALE_TEST_SUITES)

    md = [f"# Release notes · {product}", "",
          f"_Generated by DemoGraph's release agent from the knowledge graph in FalkorDB on {dt.date.today():%d %b %Y}. "
          f"Compares crawl `{crawl_id}` with {('`' + prev[0] + '`') if prev else 'nothing (first crawl)'}._", "",
          f"**Summary:** {summary}", "",
          f"{visited} pages checked, {unchanged} unchanged.", ""]
    md += ["## What changed", ""]
    if not changes:
        md.append("Nothing.")
    for page, items in by_page.items():
        md.append(f"- `{page}`")
        md += [f"  - {i}" for i in items]
    md += ["", "## What it affected", ""]
    if rebuilt:
        md.append("**Rebuilt automatically by the watcher**")
        for new, goal, olds in rebuilt:
            md.append(f"- Demo “{goal}”: `{new}` replaces {', '.join('`' + o + '`' for o in olds)} "
                      f"(new video, guide and regression test)")
        md.append("")
    if broken:
        md.append("**Broken: the feature these demos showed is gone**")
        md += [f"- Demo “{goal}” (`{d}`): {reason}" for d, goal, reason in broken]
        md.append("")
    if stale_demos or stale_suites:
        md.append("**Needs attention (not rebuilt yet)**")
        md += [f"- Demo “{r[1]}” (`{r[0]}`): {int(r[4])} of {r[3]} scenes out of date" for r in stale_demos]
        md += [f"- {kind} test suite `{path}` asserts {n} element{'s' * (n != 1)} that changed" for _, kind, path, n in stale_suites]
        md.append("")
    if not (rebuilt or broken or stale_demos or stale_suites):
        md += ["No demo, video, guide or test cited anything that changed.", ""]
    if qa_summary:
        md += ["## QA", "", qa_summary, ""]

    out = settings.data_dir / "releases" / store.name / f"{crawl_id}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(md), encoding="utf-8")
    note = ReleaseNote(id=f"release-{crawl_id}-{secrets.token_hex(2)}", crawl=crawl_id,
                       previous=prev[0] if prev else None, path=out, changes=len(changes), summary=summary)
    await store.query(Q.SAVE_RELEASE_NOTE, {"note_id": note.id, "crawl_id": crawl_id, "path": out.as_posix(),
                                            "changes": len(changes), "summary": summary, "now": int(time.time() * 1000)})
    return note
