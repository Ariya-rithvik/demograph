"""Documentation agent: a step-by-step guide for a demo, built from a verified browser replay.

Each step is one scene: its narration, an annotated screenshot zoomed on what it cites,
and the cited elements themselves. The guide is linked to its scenes in the graph, so the
same stale-citation check that flags video seconds also flags guide steps.
"""

import datetime as dt
import html
import secrets
import time
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import urlsplit

from PIL import Image

from . import queries as Q
from .config import settings
from .db import GraphStore
from .ids import origin
from .planner import product_name
from .recorder.render import decorate, focus_rect
from .recorder.replay import Replayer, SceneCapture
from .schema import apply_schema

STEP_W, STEP_H = 1200, 675


class DocError(Exception):
    pass


@dataclass
class Guide:
    doc_id: str
    markdown: Path
    html: Path
    steps: int
    citations: int


def _route(scenes: list[dict]) -> list[str]:
    route: list[str] = []
    for s in scenes:
        if not route or route[-1] != s["page_path"]:
            route.append(s["page_path"])
    return route


def _step_image(cap: SceneCapture, kind: str, out: Path) -> None:
    # A form step is clearest once filled in; every other step at the moment it starts.
    kf = cap.frames[-1] if kind == "form" else cap.frames[0]
    img = decorate(kf)
    box = tuple(int(v) for v in focus_rect(kf.marks, img.width, img.height))
    img.crop(box).resize((STEP_W, STEP_H), Image.LANCZOS).save(out, optimize=True)


def build_guide(captures: list[SceneCapture], scenes: list[dict], meta: dict, root_url: str,
                crawl_id: str, out_dir: Path) -> tuple[Path, Path, int]:
    """Write guide.md and guide.html (plus one image per step) into out_dir."""
    out_dir.mkdir(parents=True, exist_ok=True)
    product = product_name(scenes[0]["full_title"], urlsplit(root_url).netloc)
    title = f"How to {(meta['target_text'] or meta['goal']).rstrip('.')} in {product}"
    route = "  →  ".join(_route(scenes))
    stamp = f"{dt.date.today():%d %b %Y}"
    citations = 0
    md = [f"# {title}", "",
          f"_Generated by DemoGraph from {product}'s knowledge graph in FalkorDB. "
          f"Every step was replayed in a live browser and checked against the product on {stamp} "
          f"(crawl `{crawl_id}`)._", "", f"**Route:** {route}", ""]
    steps_html = []
    for i, (cap, scene) in enumerate(zip(captures, scenes), 1):
        img = f"step-{i}.png"
        _step_image(cap, scene["kind"], out_dir / img)
        cites = scene["cites"]
        citations += len(cites)
        md += [f"## Step {i}. {scene['narration']}", "", f"![Step {i}]({img})", ""]
        md += [f"> Source: {c['role']} “{c['text']}” on `{scene['page_path']}` (element `{c['fact_id']}`)" for c in cites]
        md.append("")
        chips = "".join(f'<li><span class="role">{html.escape(c["role"])}</span> “{html.escape(c["text"])}”'
                        f' <code>{html.escape(c["fact_id"])}</code></li>' for c in cites)
        steps_html.append(f"""<section class="step"><div class="num">{i}</div><div class="body">
<h2>{html.escape(scene['narration'])}</h2><p class="page">{html.escape(scene['page_path'])}</p>
<img src="{img}" alt="Step {i}"><ul class="cites">{chips}</ul></div></section>""")

    md_path = out_dir / "guide.md"
    md_path.write_text("\n".join(md), encoding="utf-8")
    html_path = out_dir / "guide.html"
    html_path.write_text(f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1"><title>{html.escape(title)}</title>
<style>
:root{{--bg:#f7f8fc;--ink:#151a2d;--dim:#5f6880;--line:#e3e6f0;--a:#6d4cff}}
body{{margin:0;background:var(--bg);color:var(--ink);font:16px/1.6 Inter,"Segoe UI",system-ui,sans-serif}}
main{{max-width:880px;margin:0 auto;padding:48px 20px 80px}}
.kicker{{font:600 12px ui-monospace,Consolas,monospace;letter-spacing:.14em;text-transform:uppercase;color:var(--a)}}
h1{{font-size:38px;line-height:1.15;margin:8px 0 12px;letter-spacing:-.02em}}
.meta{{color:var(--dim);font-size:14px}} .route{{margin:18px 0 34px;padding:12px 16px;background:#fff;border:1px solid var(--line);border-radius:12px;font:14px ui-monospace,Consolas,monospace}}
.step{{display:grid;grid-template-columns:44px 1fr;gap:16px;margin:0 0 34px}}
.num{{width:44px;height:44px;border-radius:12px;background:linear-gradient(135deg,#6d4cff,#22b8d6);color:#fff;font-weight:800;display:grid;place-items:center}}
h2{{font-size:20px;margin:6px 0 2px}} .page{{margin:0 0 12px;color:var(--dim);font:13px ui-monospace,Consolas,monospace}}
img{{width:100%;border-radius:14px;border:1px solid var(--line);box-shadow:0 10px 30px rgba(20,30,60,.08)}}
.cites{{list-style:none;padding:0;margin:10px 0 0;font-size:13px;color:var(--dim)}}
.cites code{{font-size:11px;color:#8a92a8}} .role{{display:inline-block;min-width:46px;font:600 11px ui-monospace,Consolas,monospace;color:var(--a);text-transform:uppercase}}
</style></head><body><main>
<div class="kicker">{html.escape(product)} · product guide</div><h1>{html.escape(title)}</h1>
<p class="meta">Generated by DemoGraph from the knowledge graph in FalkorDB. Every step was replayed in a live
browser and checked against the product on {stamp} (crawl <code>{html.escape(crawl_id)}</code>).</p>
<div class="route">{html.escape(route)}</div>
{''.join(steps_html)}
</main></body></html>""", encoding="utf-8")
    return md_path, html_path, citations


async def save_guide(store: GraphStore, demo_id: str, crawl_id: str, md: Path, html_path: Path,
                     title: str, scenes: list[dict]) -> str:
    doc_id = f"{demo_id}-doc-{secrets.token_hex(2)}"
    await store.query(Q.SAVE_DOC, {
        "demo_id": demo_id, "crawl_id": crawl_id, "doc_id": doc_id, "path": md.as_posix(),
        "html": html_path.as_posix(), "title": title, "now": int(time.time() * 1000),
        "sections": [{"scene_id": s["id"], "section": i} for i, s in enumerate(scenes, 1)]})
    return doc_id


async def document_demo(store: GraphStore, root_url: str, demo_id: str, headless: bool = True,
                        log=print) -> Guide:
    """Replay a demo (no video) and write its guide."""
    from .recorder import load_demo, stale_citations  # avoid a cycle: recorder imports this module
    await apply_schema(store)
    meta, scenes = await load_demo(store, demo_id)
    problems = stale_citations(scenes)
    if problems:
        raise DocError("Not documenting a stale demo (plan it again):\n  " + "\n  ".join(problems))
    crawl = await store.one(Q.LATEST_COMPLETED_CRAWL, {"site_id": origin(root_url)})
    if not crawl:
        raise DocError("No completed crawl to verify against.")
    log("Replaying the demo in Chromium and checking every citation on the live page")
    captures = await Replayer(scale=2, headless=headless).run(scenes)
    live = [p for c in captures for p in c.problems]
    if live or len(captures) != len(scenes):
        raise DocError("The live product does not match the plan:\n  " + "\n  ".join(live))
    out_dir = settings.data_dir / "docs" / store.name / demo_id
    md, html_path, citations = build_guide(captures, scenes, meta, root_url, crawl[0], out_dir)
    doc_id = await save_guide(store, demo_id, crawl[0], md, html_path, md.read_text(encoding="utf-8").splitlines()[0][2:], scenes)
    return Guide(doc_id=doc_id, markdown=md, html=html_path, steps=len(scenes), citations=citations)
