"""QA agent: generates runnable Playwright regression and smoke tests from the graph.

* Regression test, one per demo: replays the demo's steps and asserts every cited element
  says what the demo says. It uses the same replay-and-check code as the recorder.
* Smoke test, one per page of the latest crawl: the page loads, does not redirect, and its
  main heading still says what the crawl stored.

Each suite records which elements it asserts, (:TestSuite)-[:CHECKS {hash}]->(:Element),
so after a release the graph knows which tests will fail and why, and the watcher
regenerates them. Generated files are plain pytest files that can run in any CI.
"""

import asyncio
import json
import re
import secrets
import subprocess
import sys
import time
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path

from playwright.async_api import async_playwright

from . import queries as Q
from .config import settings
from .db import GraphStore
from .explorer.extract import ELEMENTS_INFO_JS
from .ids import normalize_url, origin
from .recorder.replay import Replayer
from .schema import apply_schema

ROOT = Path(__file__).resolve().parents[1]


@dataclass
class Suite:
    id: str
    kind: str  # regression | smoke
    path: Path
    tests: int
    demo: str | None = None
    passed: int | None = None
    failed: int | None = None
    failures: list[str] = field(default_factory=list)


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")[:40] or "demo"


# --- runtime used by the generated files -------------------------------------------

def run_demo(scenes: list[dict]) -> None:
    """Replay a demo in Chromium; fail with every mismatch between the plan and the live product."""
    captures = asyncio.run(Replayer(scale=1).run(scenes))
    problems = [p for c in captures for p in c.problems]
    assert not problems, "\n".join(problems)
    assert len(captures) == len(scenes), f"replay stopped after {len(captures)} of {len(scenes)} scenes"


def check_page(page: dict) -> None:
    async def run():
        async with async_playwright() as pw:
            browser = await pw.chromium.launch(args=["--disable-gpu"])
            try:
                tab = await browser.new_page(viewport={"width": 1280, "height": 720})
                resp = await tab.goto(page["url"], wait_until="domcontentloaded", timeout=20_000)
                assert resp is None or resp.ok, f"{page['path']} answered HTTP {resp.status}"
                assert normalize_url(tab.url) == normalize_url(page["url"]), f"{page['path']} redirected to {tab.url}"
                if page.get("heading"):
                    info = (await tab.evaluate(ELEMENTS_INFO_JS, [page["heading"]["selector"]]))[0]
                    assert info, f"heading of {page['path']} is gone"
                    assert info["text"] == page["heading"]["text"], \
                        f"heading of {page['path']} says “{info['text']}”, expected “{page['heading']['text']}”"
            finally:
                await browser.close()
    asyncio.run(run())


# --- generation ------------------------------------------------------------------

HEADER = '''"""Generated by DemoGraph's QA agent from the knowledge graph in FalkorDB.
{what}
Crawl {crawl}. Regenerated automatically when the product changes; do not edit by hand.
"""

import json

import pytest

from demograph.qa import {fn}
'''


async def generate_regression(store: GraphStore, demo_id: str, crawl_id: str, out_dir: Path) -> Suite:
    from .recorder import load_demo  # recorder imports heavy modules; keep import local
    meta, scenes = await load_demo(store, demo_id)
    path = out_dir / f"test_demo_{_slug(meta['goal'])}.py"
    body = HEADER.format(what=f"Regression test for demo {demo_id} ({meta['goal']!r}): replays every step and\n"
                              f"checks each cited element still says what the demo says.", crawl=crawl_id, fn="run_demo")
    body += f"\nSCENES = json.loads(r'''{json.dumps(scenes, ensure_ascii=False, indent=1)}''')\n\n\n"
    body += f"def test_{_slug(meta['goal'])}():\n    run_demo(SCENES)\n"
    path.write_text(body, encoding="utf-8")
    checks = [{"fact_id": c["fact_id"], "hash": c["current"]} for s in scenes for c in s["cites"]]
    suite = Suite(id=f"qa-{_slug(meta['goal'])}-{secrets.token_hex(2)}", kind="regression", path=path, tests=1, demo=demo_id)
    await _save(store, suite, crawl_id, checks)
    return suite


async def generate_smoke(store: GraphStore, crawl_id: str, out_dir: Path) -> Suite:
    pages = []
    for pid, url, path in await store.query(Q.CRAWL_PAGES, {"crawl_id": crawl_id}):
        head = await store.one(Q.PAGE_HEADING, {"page_id": pid})
        pages.append({"url": url, "path": path,
                      "heading": {"selector": head[1], "text": head[2], "fact_id": head[0], "hash": head[3]} if head else None})
    path = out_dir / "test_smoke_pages.py"
    body = HEADER.format(what=f"Smoke tests: each of the {len(pages)} pages loads without redirecting and its main heading\n"
                              f"still says what the crawl stored.", crawl=crawl_id, fn="check_page")
    body += f"\nPAGES = json.loads(r'''{json.dumps(pages, ensure_ascii=False, indent=1)}''')\n\n\n"
    body += "@pytest.mark.parametrize(\"page\", PAGES, ids=[p[\"path\"] for p in PAGES])\n"
    body += "def test_page(page):\n    check_page(page)\n"
    path.write_text(body, encoding="utf-8")
    checks = [{"fact_id": p["heading"]["fact_id"], "hash": p["heading"]["hash"]} for p in pages if p["heading"]]
    suite = Suite(id=f"qa-smoke-{secrets.token_hex(2)}", kind="smoke", path=path, tests=len(pages))
    await _save(store, suite, crawl_id, checks)
    return suite


async def _save(store: GraphStore, suite: Suite, crawl_id: str, checks: list[dict]) -> None:
    await store.query(Q.SAVE_TEST_SUITE, {
        "suite_id": suite.id, "kind": suite.kind, "path": suite.path.as_posix(), "tests": suite.tests,
        "now": int(time.time() * 1000), "crawl_id": crawl_id, "demo_id": suite.demo, "checks": checks})


# --- running ----------------------------------------------------------------------

def run_suite(suite: Suite) -> Suite:
    """Run a generated suite with pytest; collect pass/fail and the failure messages."""
    report = suite.path.with_suffix(".xml")
    subprocess.run([sys.executable, "-m", "pytest", str(suite.path), "-q", "-p", "no:cacheprovider",
                    "-o", "addopts=", f"--junitxml={report}"], cwd=ROOT, capture_output=True, text=True)
    root = ET.parse(report).getroot()
    cases = root.iter("testcase")
    suite.passed = suite.failed = 0
    for case in cases:
        bad = case.find("failure") if case.find("failure") is not None else case.find("error")
        if bad is None:
            suite.passed += 1
        else:
            suite.failed += 1
            msg = (bad.get("message") or "").splitlines()
            suite.failures.append(f"{case.get('name')}: {msg[0][:220] if msg else 'failed'}")
    return suite


async def record_run(store: GraphStore, suite: Suite, ms: int) -> None:
    await store.query(Q.SAVE_TEST_RUN, {"run_id": f"{suite.id}-run-{secrets.token_hex(2)}", "suite_id": suite.id,
                                        "now": int(time.time() * 1000), "passed": suite.passed,
                                        "failed": suite.failed, "ms": ms, "failures": suite.failures[:10]})


async def qa(store: GraphStore, root_url: str, demo_ids: list[str] | None = None, run: bool = True,
             smoke: bool = True, log=print) -> list[Suite]:
    """Generate (and by default run) regression tests for demos and a smoke suite for the latest crawl."""
    await apply_schema(store)
    crawl = await store.one(Q.LATEST_COMPLETED_CRAWL, {"site_id": origin(root_url)})
    if not crawl:
        raise RuntimeError("No completed crawl yet. Run `demograph explore` first.")
    out_dir = settings.data_dir / "qa" / store.name
    out_dir.mkdir(parents=True, exist_ok=True)
    if demo_ids is None:
        seen, demo_ids = set(), []
        for r in await store.query(Q.DEMO_HEALTH):  # newest first; one per goal
            if r[5] == "current" and r[1] not in seen:
                seen.add(r[1])
                demo_ids.append(r[0])
    suites = [await generate_regression(store, d, crawl[0], out_dir) for d in demo_ids]
    if smoke:
        suites.append(await generate_smoke(store, crawl[0], out_dir))
    for s in suites:
        log(f"Generated {s.kind} suite {s.path.as_posix()} ({s.tests} test{'s' * (s.tests != 1)})")
        if run:
            t0 = time.monotonic()
            await asyncio.to_thread(run_suite, s)
            await record_run(store, s, int((time.monotonic() - t0) * 1000))
            log(f"  {s.passed} passed, {s.failed} failed" + "".join(f"\n    FAIL {f}" for f in s.failures))
    return suites
